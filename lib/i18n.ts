export type TranslationKey = keyof typeof translations.gu;

export function t(key: TranslationKey, lang: Lang = "gu"): string {
  return translations[lang][key] || key;
}

// Helper to replace variables in strings like {{booking_number}}
export function interpolate(str: string, vars: Record<string, string | number>) {
  return Object.keys(vars).reduce(
    (acc, k) => acc.replace(new RegExp(`{{${k}}}`, "g"), String(vars[k])),
    str
  );
}
